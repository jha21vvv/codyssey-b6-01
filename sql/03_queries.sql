-- ------------------------------------------------------------------------------
-- Q05. [INNER JOIN] 주문 내역과 주문자의 회원 정보(이름, 등급, 전화번호) 매칭 조회
-- [쿼리 목적]: 각 영수증이 어떤 회원의 주문인지 주문자와 결제 정보를 한눈에 결합 확인
-- ------------------------------------------------------------------------------
-- [1차]: 주문 ID, 고객 이름, 등급, 전화번호, 결제 금액, 결제 상태를 선택합니다.
-- [2차]: 영수증 번호 옆에 손님의 실명과 고객 등급 명찰을 나란히 붙여서 확인합니다.
SELECT o.order_id, m.name AS member_name, m.grade, m.phone, o.total_amount, o.order_status
-- [1차]: 주문 테이블 orders를 기준(별칭 o)으로 설정합니다.
-- [2차]: 결제 영수증 더미(o)를 책상 왼쪽에 올려놓습니다.
FROM orders o
-- [1차]: members 테이블(별칭 m)과 member_id가 일치하는 행끼리 내부 조인(INNER JOIN)합니다.
-- [2차]: 영수증에 적힌 회원번호를 보고, 오른쪽 회원 수첩(m)에서 동일한 번호의 손님 인적사항을 찾아 풀로 딱 붙입니다.
INNER JOIN members m ON o.member_id = m.member_id
-- [1차]: 주문 ID 오름차순으로 정렬합니다.
-- [2차]: 1번 영수증부터 차례대로 가지런히 정리합니다.
ORDER BY o.order_id ASC;

-- ------------------------------------------------------------------------------
-- Q06. [INNER JOIN - 3개 테이블 다중 조인] 주문 상세 내역과 메뉴명, 카테고리명 결합 조회
-- [쿼리 목적]: 주방 바리스타가 주문서를 보고 어떤 카테고리의 어떤 메뉴를 제조해야 하는지 상세 확인
-- ------------------------------------------------------------------------------
-- [1차]: 주문상세 ID, 주문 ID, 카테고리명, 메뉴명, 수량, 판매단가, 계산된 품목 총액을 선택합니다.
-- [2차]: 바리스타 주문서에 '주문번호, 음료 종류, 메뉴명, 잔 수, 단가, 총금액'을 일목요연하게 표시합니다.
SELECT 
    oi.order_item_id,
    oi.order_id,
    c.category_name,
    m.menu_name,
    oi.quantity,
    oi.unit_price,
    (oi.quantity * oi.unit_price) AS line_total
-- [1차]: 주문 품목 테이블(order_items, 별칭 oi)을 주 테이블로 지정합니다.
-- [2차]: 영수증 속 세부 품목 한 줄 한 줄(oi)을 펼칩니다.
FROM order_items oi
-- [1차]: 메뉴 테이블(menus, 별칭 m)과 menu_id로 조인하여 메뉴 이름을 가져옵니다.
-- [2차]: 품목에 적힌 메뉴 바코드 번호를 메뉴판(m)과 대조해 '아메리카노', '초코라떼' 같은 메뉴 이름을 알아냅니다.
INNER JOIN menus m ON oi.menu_id = m.menu_id
-- [1차]: 카테고리 테이블(categories, 별칭 c)과 category_id로 조인하여 대분류를 가져옵니다.
-- [2차]: 그 메뉴가 '커피 서랍(c)'에 있는지 '디저트 서랍(c)'에 있는지 분류 꼬리표를 확인합니다.
INNER JOIN categories c ON m.category_id = c.category_id
-- [1차]: 주문 ID 오름차순, 주문 품목 ID 오름차순으로 정렬합니다.
-- [2차]: 주문 영수증 순서대로, 그리고 그 영수증 안의 첫 번째 줄부터 순서대로 나열합니다.
ORDER BY oi.order_id ASC, oi.order_item_id ASC;

-- ------------------------------------------------------------------------------
-- Q07. [LEFT JOIN] 회원 테이블 기준 주문 이력 조회 (한 번도 주문 안 한 신규/휴면 회원 발굴)
-- [쿼리 목적]: 회원가입만 하고 아직 한 번도 구매하지 않은 고객을 찾아 웰컴 할인 쿠폰 발송
-- ------------------------------------------------------------------------------
-- [1차]: 회원 ID, 이름, 이메일, 가입일, 주문 ID를 선택합니다.
-- [2차]: 전체 고객 명부에서 이름과 가입일을 확인하고, 주문 영수증이 붙어 있는지 확인합니다.
SELECT m.member_id, m.name, m.email, m.created_at, o.order_id
-- [1차]: members 테이블을 왼쪽 기준 테이블로 지정합니다.
-- [2차]: 카페에 가입한 모든 고객(m)을 빠짐없이 출석부에 세웁니다.
FROM members m
-- [1차]: orders 테이블과 LEFT JOIN하여 주문이 없는 회원도 누락 없이 NULL로 유지합니다.
-- [2차]: 각 손님 옆에 그 손님이 결제한 영수증(o)을 나란히 놓되, 주문한 적이 없는 손님 옆은 빈칸(NULL)으로 둡니다.
LEFT JOIN orders o ON m.member_id = o.member_id
-- [1차]: 오른쪽 주문 테이블의 order_id가 NULL인 행만 필터링합니다.
-- [2차]: 영수증 자리가 텅 빈(NULL) 손님, 즉 가입만 하고 커피를 한 번도 안 사 마신 신규/미구매 고객만 콕 집어냅니다.
WHERE o.order_id IS NULL;

-- ------------------------------------------------------------------------------
-- Q08. [LEFT JOIN + COALESCE] 전체 메뉴별 판매 집계 (주문 실적이 없는 비인기 메뉴도 0개로 표시)
-- [쿼리 목적]: 메뉴판의 모든 메뉴가 몇 개씩 팔렸는지 전수 조사하여 메뉴 개편/단종 여부 판단
-- ------------------------------------------------------------------------------
-- [1차]: 메뉴 ID, 메뉴명, 정가, NULL을 0으로 치환한 총 주문 수량을 선택합니다.
-- [2차]: 메뉴 이름과 가격, 그리고 여태까지 팔린 총 잔 수를 보여주되, 한 잔도 안 팔린 메뉴는 빈칸 대신 숫자 0으로 예쁘게 채웁니다.
SELECT 
    m.menu_id,
    m.menu_name,
    m.price,
    COALESCE(SUM(oi.quantity), 0) AS total_sold_quantity
-- [1차]: 전체 메뉴 테이블(menus, 별칭 m)을 왼쪽 기준 테이블로 지정합니다.
-- [2차]: 메뉴판에 적힌 모든 메뉴(m)를 하나도 빠짐없이 칠판에 적습니다.
FROM menus m
-- [1차]: 주문 품목 테이블(order_items, 별칭 oi)과 LEFT JOIN합니다.
-- [2차]: 손님들이 주문한 품목 영수증 조각(oi)들을 해당 메뉴 이름 밑에 모아 붙입니다.
LEFT JOIN order_items oi ON m.menu_id = oi.menu_id
-- [1차]: 메뉴 ID와 메뉴명으로 그룹화합니다.
-- [2차]: 같은 메뉴 이름별로 묶어 서랍 하나에 담습니다.
GROUP BY m.menu_id, m.menu_name, m.price
-- [1차]: 판매 수량이 높은 순서(내림차순)로 정렬합니다.
-- [2차]: 가장 불티나게 팔린 베스트셀러 메뉴부터 맨 위에 줄을 세웁니다.
ORDER BY total_sold_quantity DESC;

