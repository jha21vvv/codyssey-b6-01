-- ------------------------------------------------------------------------------
-- Q09. [COUNT, AVG, MAX + GROUP BY] 카테고리별 등록 메뉴 수, 평균 가격, 최고 가격 집계
-- [쿼리 목적]: 카테고리별 가격대 분포와 상품 구색 현황을 파악하여 메뉴 가격 정책 수립
-- ------------------------------------------------------------------------------
-- [1차]: 카테고리 ID, 카테고리명, 메뉴 개수(COUNT), 평균 가격(AVG 반올림), 최고 가격(MAX)을 계산합니다.
-- [2차]: 각 코너별로 등록된 메뉴가 몇 개인지 세고, 평균 가격과 제일 비싼 메뉴 가격표를 뽑아냅니다.
SELECT 
    c.category_id,
    c.category_name,
    COUNT(m.menu_id) AS menu_count,
    ROUND(AVG(m.price), 0) AS avg_price,
    MAX(m.price) AS max_price
-- [1차]: 카테고리 테이블을 기준으로 메뉴 테이블과 INNER JOIN합니다.
-- [2차]: 카테고리 서랍(c)과 거기에 속한 메뉴 카드들(m)을 짝짓습니다.
FROM categories c
INNER JOIN menus m ON c.category_id = m.category_id
-- [1차]: 카테고리 ID와 카테고리 이름으로 그룹화합니다.
-- [2차]: '커피팀', '디저트팀', '차팀' 등으로 모둠을 만듭니다.
GROUP BY c.category_id, c.category_name
-- [1차]: 카테고리 ID 순으로 정렬합니다.
-- [2차]: 1번 카테고리부터 차례대로 깔끔하게 성적표를 출력합니다.
ORDER BY c.category_id ASC;

-- ------------------------------------------------------------------------------
-- Q10. [COUNT, SUM + GROUP BY] 고객별 총 결제 횟수 및 누적 구매 금액 집계
-- [쿼리 목적]: 고객별 LTV(고객 생애 가치)를 산출하여 충성 고객 순위 산정
-- ------------------------------------------------------------------------------
-- [1차]: 회원 ID, 이름, 등급, 총 주문 건수(COUNT), 누적 결제 총액(SUM)을 계산합니다.
-- [2차]: 손님마다 몇 번 결제했는지 횟수를 세고, 우리 카페에 쓴 총 결제 금액을 합산합니다.
SELECT 
    m.member_id,
    m.name AS member_name,
    m.grade,
    COUNT(o.order_id) AS order_count,
    SUM(o.total_amount) AS total_spent
-- [1차]: 회원 테이블과 주문 테이블을 내부 조인합니다.
-- [2차]: 결제 내역이 있는 손님(m)과 그 손님의 영수증들(o)을 묶습니다.
FROM members m
INNER JOIN orders o ON m.member_id = o.member_id
-- [1차]: 취소되지 않고 유효한 주문('COMPLETED', 'PAID')만 집계에 반영합니다.
-- [2차]: 도중에 결제 취소한 영수증은 매출에서 쏙 빼고 정상 영수증만 합칩니다.
WHERE o.order_status IN ('COMPLETED', 'PAID')
-- [1차]: 회원 단위로 그룹화합니다.
-- [2차]: 손님 이름별로 영수증을 모아 작은 더미를 만듭니다.
GROUP BY m.member_id, m.name, m.grade
-- [1차]: 총 결제 금액 기준 내림차순 정렬합니다.
-- [2차]: 우리 매장에 가장 많은 돈을 써주신 고마운 손님부터 1등, 2등 순서로 랭킹을 매깁니다.
ORDER BY total_spent DESC;

-- ------------------------------------------------------------------------------
-- Q11. [GROUP BY + HAVING] 2회 이상 주문한 단골 고객 및 총 주문 금액 필터링
-- [쿼리 목적]: 단순 일회성 방문 고객을 제외하고, 2회 이상 재방문한 찐단골만 선별
-- ------------------------------------------------------------------------------
-- [1차]: 회원 ID, 이름, 주문 횟수, 총 결제액을 선택합니다.
-- [2차]: 단골 전용 VIP 혜택을 드리기 위해 손님 이름과 방문 횟수를 확인합니다.
SELECT 
    m.member_id,
    m.name AS member_name,
    COUNT(o.order_id) AS repeat_orders,
    SUM(o.total_amount) AS total_spent
-- [1차]: members와 orders를 조인합니다.
-- [2차]: 손님 명부와 결제 영수증을 결합합니다.
FROM members m
INNER JOIN orders o ON m.member_id = o.member_id
-- [1차]: 결제 유효 건만 대상으로 합니다.
-- [2차]: 유효한 결제 영수증만 카운트합니다.
WHERE o.order_status IN ('COMPLETED', 'PAID')
-- [1차]: 회원별로 그룹화합니다.
-- [2차]: 손님별로 묶어 그룹 바구니를 만듭니다.
GROUP BY m.member_id, m.name
-- [1차]: 집계된 주문 건수가 2건 이상인 그룹만 HAVING 절로 통과시킵니다.
-- [2차]: 한 번만 방문하고 가신 분들은 거르고, 매장에 최소 2번 이상 오신 단골 바구니만 쏙 골라냅니다.
HAVING COUNT(o.order_id) >= 2
-- [1차]: 재방문 횟수 내림차순 정렬합니다.
-- [2차]: 가장 자주 찾아오신 손님부터 줄을 세웁니다.
ORDER BY repeat_orders DESC, total_spent DESC;

