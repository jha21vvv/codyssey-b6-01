-- ------------------------------------------------------------------------------
-- Q12. [중첩 서브쿼리] 전체 메뉴의 평균 가격보다 비싼 고급 메뉴 목록 조회
-- [쿼리 목적]: 메뉴 전체 평균 단가를 자동 계산하고, 그보다 높은 고부가가치 메뉴 선별
-- ------------------------------------------------------------------------------
-- [1차]: 메뉴 ID, 메뉴명, 가격 컬럼을 프로젝션합니다.
-- [2차]: 프리미엄 메뉴 추천 리스트에 띄울 메뉴 번호와 이름, 가격을 가져옵니다.
SELECT menu_id, menu_name, price
-- [1차]: menus 테이블에서 조회합니다.
-- [2차]: 메뉴판 서랍을 엽니다.
FROM menus
-- [1차]: 가격이 서브쿼리로 계산된 전체 메뉴 평균 가격보다 큰 행만 비교 필터링합니다.
-- [2차]: 서브쿼리 계산기(괄호 안)가 먼저 전체 메뉴의 평균 가격(약 7,200원)을 구한 뒤, 그 기준선보다 비싼 고급 메뉴만 쏙 뽑아냅니다.
WHERE price > (
    -- [1차]: 전체 menus 테이블의 price 평균값을 단일 스칼라(Scalar) 값으로 반환하는 서브쿼리입니다.
    -- [2차]: 카페 전체 메뉴들의 평균 가격을 구하는 보조 계산기입니다.
    SELECT AVG(price) FROM menus
)
-- [1차]: 가격 내림차순으로 정렬합니다.
-- [2차]: 가장 비싼 프리미엄 메뉴부터 맨 위에 나열합니다.
ORDER BY price DESC;

