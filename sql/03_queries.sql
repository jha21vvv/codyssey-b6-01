-- ------------------------------------------------------------------------------
-- Q13. [UPDATE] 누적 결제액 30,000원 이상인 일반 회원을 VIP로 승급 및 포인트 2,000점 지급
-- [쿼리 목적]: 결제 실적 기반 회원 등급 자동 승급 및 리워드 포인트 지급 비즈니스 로직
-- ------------------------------------------------------------------------------
-- [1차]: members 테이블의 grade와 points 컬럼 값을 수정합니다.
-- [2차]: 단골 자격을 획득한 손님의 명찰을 'VIP'로 바꿔 달아드리고, 보너스 포인트 2,000점을 통장에 얹어 드립니다.
UPDATE members
SET grade = 'VIP',
    points = points + 2000
-- [1차]: 수정 대상이 되는 회원을 서브쿼리로 필터링합니다.
-- [2차]: 과거 유효 결제 총액이 30,000원을 돌파한 우수 고객님들의 회원번호를 찾아서 그분들만 승급시킵니다.
WHERE member_id IN (
    -- [1차]: 결제 완료된 주문의 총합이 30,000원 이상인 회원 ID를 도출하는 서브쿼리입니다.
    -- [2차]: 누적 결제액 3만 원 이상을 달성한 VIP 승급 대상자 명단을 추리는 집계 계산기입니다.
    SELECT o.member_id
    FROM orders o
    WHERE o.order_status IN ('COMPLETED', 'PAID')
    GROUP BY o.member_id
    HAVING SUM(o.total_amount) >= 30000
)
-- [1차]: 이미 VIP나 VVIP인 회원은 제외하고 NORMAL 등급만 승급 대상으로 지정합니다.
-- [2차]: 이미 최고 등급이신 분들은 건너뛰고, 일반(NORMAL) 등급이었던 분들만 VIP로 올려드립니다.
AND grade = 'NORMAL';

