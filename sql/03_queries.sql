-- ------------------------------------------------------------------------------
-- Q01. 판매 중인 메뉴 목록을 가격이 비싼 순서로 상위 5개 조회
-- [쿼리 목적]: 현재 메뉴판에 활성화(판매중)된 프리미엄 메뉴 TOP 5를 확인하여 주력 상품 파악
-- ------------------------------------------------------------------------------
-- [1차]: 메뉴 ID, 이름, 가격 컬럼을 프로젝션(SELECT)합니다.
-- [2차]: 메뉴판에서 손님에게 보여줄 '메뉴 번호, 이름, 가격표' 3가지만 골라냅니다.
SELECT menu_id, menu_name, price
-- [1차]: menus 테이블에서 데이터를 가져옵니다.
-- [2차]: 카페 전체 메뉴 카드가 꽂혀 있는 메뉴판 서랍을 엽니다.
FROM menus
-- [1차]: 판매 가능(is_available = 1) 플래그를 가진 레코드만 필터링합니다.
-- [2차]: 현재 품절 딱지가 붙지 않고 정상 판매 중인 메뉴들만 쏙쏙 추려냅니다.
WHERE is_available = 1
-- [1차]: 가격(price)을 기준으로 내림차순(DESC) 정렬합니다.
-- [2차]: 가장 비싸고 고급스러운 프리미엄 메뉴부터 맨 위에 오도록 줄을 세웁니다.
ORDER BY price DESC
-- [1차]: 결과 집합의 상위 5개 행만 제한하여 반환합니다.
-- [2차]: 줄 세운 메뉴들 중에서 가장 비싼 5개만 골라 VIP 추천판에 올립니다.
LIMIT 5;

-- ------------------------------------------------------------------------------
-- Q02. VIP 이상 등급 회원의 이름, 이메일, 포인트 및 가입일 조회
-- [쿼리 목적]: 로열티 프로그램 대상자(VIP/VVIP)를 필터링하여 맞춤형 감사 프로모션 발송 명단 확보
-- ------------------------------------------------------------------------------
-- [1차]: 회원 ID, 이름, 이메일, 등급, 포인트 컬럼을 선택합니다.
-- [2차]: 우수 고객 감사 선물을 보내기 위해 고객 수첩에서 이름, 연락처, 적립 포인트를 확인합니다.
SELECT member_id, name, email, grade, points
-- [1차]: members 테이블을 조회 대상으로 지정합니다.
-- [2차]: 전체 고객 명단이 적힌 회원 명부 책장을 엽니다.
FROM members
-- [1차]: 회원 등급이 'VIP' 또는 'VVIP' 집합에 포함되는 조건만 필터링합니다.
-- [2차]: 명찰에 VIP나 VVIP 도장이 쾅 찍혀 있는 특별 고객들만 골라냅니다.
WHERE grade IN ('VIP', 'VVIP')
-- [1차]: 보유 포인트를 기준으로 가장 많은 순서대로 내림차순 정렬합니다.
-- [2차]: 스탬프 포인트를 가장 많이 모아둔 진정한 카페 찐팬 순서대로 줄을 세웁니다.
ORDER BY points DESC;

-- ------------------------------------------------------------------------------
-- Q03. 결제 완료된 주문 중 15,000원 이상 고액 결제 건 조회
-- [쿼리 목적]: 단체 주문이나 선물용 고액 구매 건을 선별하여 매출 기여도가 높은 주문 패턴 분석
-- ------------------------------------------------------------------------------
-- [1차]: 주문 ID, 회원 ID, 결제 상태, 결제 금액, 결제 수단, 주문 일시를 선택합니다.
-- [2차]: 매출 분석을 위해 영수증에서 영수증 번호, 결제 금액, 결제 수단 정보를 확인합니다.
SELECT order_id, member_id, order_status, total_amount, payment_method, ordered_at
-- [1차]: orders 테이블에서 조회합니다.
-- [2차]: 카운터 포스기에서 출력된 결제 영수증 보관함을 엽니다.
FROM orders
-- [1차]: 결제 상태가 'COMPLETED' 또는 'PAID'이고 총액이 15,000원 이상인 복합 조건을 검사합니다.
-- [2차]: 주문이 정상적으로 완료되었으면서 영수증 금액이 15,000원을 넘는 묵직한 고액 영수증만 뽑아냅니다.
WHERE order_status IN ('COMPLETED', 'PAID')
  AND total_amount >= 15000
-- [1차]: 주문 일시 기준으로 가장 최근 주문부터 내림차순 정렬합니다.
-- [2차]: 가장 최근에 발생한 따끈따끈한 고액 결제 영수증부터 위로 올려놓습니다.
ORDER BY ordered_at DESC;

-- ------------------------------------------------------------------------------
-- Q04. 신용카드(CARD)로 결제된 주문을 최신순으로 3건씩 페이징(Paging) 조회
-- [쿼리 목적]: 결제 단말기 카드 전표 대조를 위해 최근 카드 매출 3건을 1페이지 단위로 조회
-- ------------------------------------------------------------------------------
-- [1차]: 주문 ID, 회원 ID, 결제 금액, 주문 일시를 선택합니다.
-- [2차]: 카드사 승인 내역과 맞추기 위해 영수증 번호와 결제 시각, 금액을 확인합니다.
SELECT order_id, member_id, total_amount, ordered_at
-- [1차]: orders 테이블을 조회합니다.
-- [2차]: 주문 영수증 파일함을 엽니다.
FROM orders
-- [1차]: 결제 수단이 'CARD'인 주문만 필터링합니다.
-- [2차]: 현금이나 카카오페이를 제외하고 오직 실물 신용카드로 긁은 영수증만 추립니다.
WHERE payment_method = 'CARD'
-- [1차]: 최신 주문 시각을 기준으로 내림차순 정렬합니다.
-- [2차]: 방금 긁은 최신 카드 결제 전표부터 맨 위에 오도록 정렬합니다.
ORDER BY ordered_at DESC
-- [1차]: 한 페이지에 3개 행만 표시하도록 제한(LIMIT)하고 첫 번째 페이지(OFFSET 0)를 지정합니다.
-- [2차]: 모바일 화면 한 페이지에 영수증을 딱 3장씩만 보여주기 위해 첫 장부터 3장만 끊어서 가져옵니다.
LIMIT 3 OFFSET 0;

