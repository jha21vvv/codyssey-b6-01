-- ------------------------------------------------------------------------------
-- Q15. [CREATE INDEX + EXPLAIN QUERY PLAN]
-- [적용 이유]: 대규모 서비스에서 회원별/주문일시별 주문 내역 조회 쿼리가 가장 빈번하므로,
--             (member_id, ordered_at) 복합 인덱스를 생성하여 풀 테이블 스캔(Full Scan)을
--             방지하고 O(log N) 인덱스 스캔(Index Scan)으로 조회 속도를 비약적으로 단축합니다.
-- ------------------------------------------------------------------------------
-- [1차]: orders 테이블의 member_id와 ordered_at 컬럼을 결합한 복합 B-Tree 인덱스를 생성합니다.
-- [2차]: 도서관에서 책을 찾기 쉽게 '손님 회원번호와 주문 날짜'가 적힌 빠른 색인용 인덱스 견출지 스티커를 만듭니다.
CREATE INDEX IF NOT EXISTS idx_orders_member_ordered_at 
ON orders (member_id, ordered_at DESC);

-- [1차]: 특정 회원의 최근 주문을 조회할 때 인덱스가 실제로 활용되는지 실행 계획(EXPLAIN QUERY PLAN)으로 확인합니다.
-- [2차]: 영수증을 찾을 때 보관함을 처음부터 끝까지 다 뒤지는지(Full Scan), 방금 만든 색인 스티커(Index Scan)를 타고 바로 찾아가는지 돋보기로 확인합니다.
EXPLAIN QUERY PLAN
SELECT order_id, total_amount, ordered_at
FROM orders
WHERE member_id = 1
ORDER BY ordered_at DESC;
