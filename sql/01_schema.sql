-- ==============================================================================
-- 스마트 카페 주문 시스템 (Smart Cafe Ordering Database)
-- 파일명: sql/01_schema.sql
-- 설명: 데이터베이스 테이블 생성(DDL) 및 무결성 제약조건 정의 스크립트
-- ==============================================================================

-- [1차]: SQLite 엔진에서 외래키(Foreign Key) 참조 무결성 검사를 강제로 활성화합니다.
-- [2차]: 자물쇠를 채워두지 않으면 엉뚱한 부모 번호를 가진 고아 데이터가 몰래 들어올 수 있으므로 현관문 보안 시스템을 켭니다.
PRAGMA foreign_keys = ON;

-- [1차]: 기존에 동일한 이름의 자식 테이블(order_items)이 존재할 경우 삭제합니다.
-- [2차]: 리모델링 공사 전, 부모 테이블을 지우려면 먼저 자식 테이블 방부터 깨끗이 비워야 합니다.
DROP TABLE IF EXISTS order_items;

-- [1차]: 기존에 동일한 이름의 주문 테이블(orders)이 존재할 경우 삭제합니다.
-- [2차]: 주문 상세 방을 비운 다음, 주문서 책상을 안전하게 치웁니다.
DROP TABLE IF EXISTS orders;

-- [1차]: 기존에 동일한 이름의 메뉴 테이블(menus)이 존재할 경우 삭제합니다.
-- [2차]: 카테고리 간판을 내리기 전에, 메뉴판 메뉴 목록을 먼저 안전하게 정리합니다.
DROP TABLE IF EXISTS menus;

-- [1차]: 기존에 동일한 이름의 카테고리 테이블(categories)이 존재할 경우 삭제합니다.
-- [2차]: 메뉴들이 모두 치워졌으므로 이제 카테고리 분류 서랍장을 철거합니다.
DROP TABLE IF EXISTS categories;

-- [1차]: 기존에 동일한 이름의 회원 테이블(members)이 존재할 경우 삭제합니다.
-- [2차]: 주문 내역이 모두 정리되었으므로 이제 회원 명부 서랍장을 철거합니다.
DROP TABLE IF EXISTS members;

-- ==============================================================================
-- 1. members 테이블: 고객 및 회원 정보 관리
-- ==============================================================================
-- [1차]: 회원(members) 정보를 저장하는 독립 테이블을 생성합니다.
-- [2차]: 카페 단골 고객들의 명함을 차곡차곡 모아둘 새 회원 수첩을 만듭니다.
CREATE TABLE members (
    -- [1차]: 정수형 기본키(PK)로 자동 증가(AUTOINCREMENT) 속성을 부여합니다.
    -- [2차]: 손님이 올 때마다 1번, 2번, 3번처럼 자동으로 번호표를 발급해 주는 고객 고유 식별 번호입니다.
    member_id INTEGER PRIMARY KEY AUTOINCREMENT,

    -- [1차]: 가변 문자열이며 중복이 불가능(UNIQUE)하고 빈 값을 허용하지 않습니다(NOT NULL).
    -- [2차]: 로그인 아이디 역할을 하는 이메일은 절대 비워둘 수 없고, 다른 사람과 겹쳐서도 안 되는 주민번호 같은 존재입니다.
    email TEXT NOT NULL UNIQUE,

    -- [1차]: 고객의 실명을 저장하며 빈 값을 허용하지 않습니다(NOT NULL).
    -- [2차]: 음료가 나왔을 때 불러드릴 손님의 이름이므로 절대 비워둘 수 없습니다.
    name TEXT NOT NULL,

    -- [1차]: 고객 연락처를 저장하며 빈 값을 허용하지 않습니다(NOT NULL).
    -- [2차]: 주문 완료 알림 문자를 전송해야 하므로 전화번호는 필수 입력 사항입니다.
    phone TEXT NOT NULL,

    -- [1차]: 고객 등급을 저장하며 지정된 세 가지 문자열 중 하나만 허용(CHECK 제약조건)하고 기본값은 'NORMAL'입니다.
    -- [2차]: 손님 등급은 오직 일반(NORMAL), 우수(VIP), 최우수(VVIP) 3개 등급만 가능하며 처음 오신 분은 일반 등급 명찰을 받습니다.
    grade TEXT NOT NULL DEFAULT 'NORMAL' CHECK(grade IN ('NORMAL', 'VIP', 'VVIP')),

    -- [1차]: 누적 포인트를 저장하는 정수형 컬럼으로 음수 방지 CHECK 및 기본값 0을 적용합니다.
    -- [2차]: 카페 스탬프 포인트는 0점부터 시작하며, 포인트 통장이 마이너스가 되는 황당한 상황을 방지합니다.
    points INTEGER NOT NULL DEFAULT 0 CHECK(points >= 0),

    -- [1차]: 가입 일시를 기록하며 기본값으로 레코드 생성 시점의 현재 시각을 자동 저장합니다.
    -- [2차]: 회원이 가입 도장을 찍는 순간의 날짜와 시간을 시스템 시계가 자동으로 기록합니다.
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ==============================================================================
-- 2. categories 테이블: 음료 및 디저트 메뉴 대분류
-- ==============================================================================
-- [1차]: 메뉴의 상위 분류(커피, 에이드, 베이커리 등)를 정의하는 카테고리 테이블을 생성합니다.
-- [2차]: 카페 메뉴판의 큰 섹션 제목(커피류, 차류, 빵류)을 분류해 둘 카테고리 서랍장을 만듭니다.
CREATE TABLE categories (
    -- [1차]: 카테고리 식별용 정수형 기본키입니다.
    -- [2차]: 각 메뉴 분류 섹션에 붙이는 고유 번호표(1: 커피, 2: 논커피 등)입니다.
    category_id INTEGER PRIMARY KEY AUTOINCREMENT,

    -- [1차]: 카테고리 이름으로 고유해야 하며 빈 값을 허용하지 않습니다.
    -- [2차]: '커피'라는 카테고리가 메뉴판에 두 번 중복해서 생기면 손님이 혼란스러우므로 유일해야 합니다.
    category_name TEXT NOT NULL UNIQUE,

    -- [1차]: 카테고리에 대한 추가 설명 텍스트 컬럼입니다.
    -- [2차]: 손님에게 해당 카테고리가 어떤 음료들인지 소개해 주는 친절한 안내 문구입니다.
    description TEXT
);

-- ==============================================================================
-- 3. menus 테이블: 판매 음료 및 푸드 상세 메뉴
-- ==============================================================================
-- [1차]: 개별 메뉴 상품의 정보를 관리하는 테이블을 생성합니다.
-- [2차]: 카페에서 판매하는 실제 음료와 디저트 하나하나의 상세 정보가 적힌 개별 메뉴 카드들을 모읍니다.
CREATE TABLE menus (
    -- [1차]: 메뉴 식별용 정수형 기본키입니다.
    -- [2차]: '아메리카노', '카페라떼' 등 각 메뉴 상품에 매겨진 고유 바코드 번호입니다.
    menu_id INTEGER PRIMARY KEY AUTOINCREMENT,

    -- [1차]: categories 테이블의 category_id를 참조하는 외래키(FK) 컬럼입니다. (1:N 관계)
    -- [2차]: 이 메뉴가 메뉴판의 어떤 분류 섹션(부모 서랍)에 속해 있는지 가리키는 꼬리표입니다.
    category_id INTEGER NOT NULL,

    -- [1차]: 메뉴 명칭을 저장하며 필수 입력입니다.
    -- [2차]: 상품의 이름이 없으면 주문을 받을 수 없으므로 이름은 필수입니다.
    menu_name TEXT NOT NULL,

    -- [1차]: 판매 정가를 저장하며 0보다 커야 하는 CHECK 제약조건을 부여합니다.
    -- [2차]: 커피 가격이 0원이거나 마이너스면 가게가 망하므로 무조건 0원 초과 금액만 허용합니다.
    price INTEGER NOT NULL CHECK(price > 0),

    -- [1차]: 품절 여부를 나타내는 불리언(0 또는 1) 플래그 컬럼입니다. 기본값 1(판매중).
    -- [2차]: 재료가 떨어졌을 때 메뉴판에 '품절' 딱지를 붙이거나 떼는 스위치(1은 판매중, 0은 품절)입니다.
    is_available INTEGER NOT NULL DEFAULT 1 CHECK(is_available IN (0, 1)),

    -- [1차]: 메뉴 등록 일시를 저장합니다.
    -- [2차]: 신메뉴가 출시되어 메뉴판에 처음 등록된 날짜를 기록합니다.
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- [1차]: 외래키 제약조건: categories의 category_id를 참조하며 부모 카테고리 삭제 시 차단(RESTRICT)합니다.
    -- [2차]: 메뉴가 남아있는데 부모 카테고리를 갑자기 없애버리면 고아 메뉴가 되므로 함부로 지우지 못하게 막습니다.
    FOREIGN KEY (category_id) REFERENCES categories (category_id) ON DELETE RESTRICT
);

-- ==============================================================================
-- 4. orders 테이블: 고객의 주문 영수증 헤더
-- ==============================================================================
-- [1차]: 고객의 주문 기본 정보를 관리하는 마스터 주문 테이블을 생성합니다.
-- [2차]: 고객이 카운터나 키오스크에서 결제할 때 한 번에 발행되는 주문 영수증의 겉표지입니다.
CREATE TABLE orders (
    -- [1차]: 주문 식별용 정수형 기본키입니다.
    -- [2차]: 영수증 상단에 인쇄되는 세상에 단 하나뿐인 주문 영수증 번호입니다.
    order_id INTEGER PRIMARY KEY AUTOINCREMENT,

    -- [1차]: members 테이블의 member_id를 참조하는 외래키(FK) 컬럼입니다. (1:N 관계)
    -- [2차]: 이 영수증이 어떤 단골 회원 손님이 주문한 것인지 가리키는 손님 회원번호입니다.
    member_id INTEGER NOT NULL,

    -- [1차]: 주문 상태를 정의하며 지정된 4개 상태 중 하나만 허용합니다.
    -- [2차]: 주문 접수(PENDING), 결제완료(PAID), 취소(CANCELLED), 픽업완료(COMPLETED) 상태를 추적합니다.
    order_status TEXT NOT NULL DEFAULT 'PAID' CHECK(order_status IN ('PENDING', 'PAID', 'CANCELLED', 'COMPLETED')),

    -- [1차]: 해당 주문의 총 결제 금액을 기록합니다.
    -- [2차]: 이 주문 영수증에 적힌 모든 음료 가격을 다 더한 최종 영수증 총액입니다.
    total_amount INTEGER NOT NULL DEFAULT 0 CHECK(total_amount >= 0),

    -- [1차]: 결제 수단(CARD, CASH, POINT, KAKAO_PAY)을 저장합니다.
    -- [2차]: 손님이 신용카드, 현금, 포인트, 카카오페이 중 무엇으로 돈을 냈는지 표시합니다.
    payment_method TEXT NOT NULL CHECK(payment_method IN ('CARD', 'CASH', 'POINT', 'KAKAO_PAY')),

    -- [1차]: 주문이 발생한 일시를 기록합니다.
    -- [2차]: 카운터에서 포스기 결제 버튼을 누른 정확한 시각입니다.
    ordered_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- [1차]: 외래키 제약: 회원이 삭제되려고 할 때 기존 주문 내역이 있으면 삭제를 방지(RESTRICT)합니다.
    -- [2차]: 과거 결제 영수증이 남아있는 손님은 회계 감사를 위해 회원 명부에서 함부로 없앨 수 없습니다.
    FOREIGN KEY (member_id) REFERENCES members (member_id) ON DELETE RESTRICT
);

-- ==============================================================================
-- 5. order_items 테이블: 주문 영수증 내의 세부 주문 품목 (N:M 해소 중간 테이블)
-- ==============================================================================
-- [1차]: 한 번의 주문에 담긴 개별 메뉴와 수량 정보를 보관하는 상세 테이블을 생성합니다.
-- [2차]: 영수증 안쪽에 적힌 "아메리카노 2잔, 치즈케이크 1개"처럼 줄줄이 적히는 상세 구매 품목 목록입니다.
CREATE TABLE order_items (
    -- [1차]: 주문 상세 품목 식별용 정수형 기본키입니다.
    -- [2차]: 영수증 속 세부 품목 한 줄 한 줄마다 매겨지는 고유 일련번호입니다.
    order_item_id INTEGER PRIMARY KEY AUTOINCREMENT,

    -- [1차]: orders 테이블의 order_id를 참조하는 외래키(FK) 컬럼입니다. (1:N 관계)
    -- [2차]: 이 품목 줄이 몇 번 주문 영수증에 적혀 있는 것인지 묶어주는 영수증 번호입니다.
    order_id INTEGER NOT NULL,

    -- [1차]: menus 테이블의 menu_id를 참조하는 외래키(FK) 컬럼입니다. (1:N 관계)
    -- [2차]: 주문한 메뉴가 메뉴판의 어떤 메뉴인지 가리키는 메뉴 식별 바코드 번호입니다.
    menu_id INTEGER NOT NULL,

    -- [1차]: 주문한 메뉴의 수량으로 1개 이상이어야 합니다.
    -- [2차]: 음료를 몇 잔 시켰는지 나타내며, 0잔이나 마이너스 잔 주문은 있을 수 없으므로 1 이상이어야 합니다.
    quantity INTEGER NOT NULL CHECK(quantity > 0),

    -- [1차]: 주문 발생 시점의 개별 메뉴 단가를 저장합니다.
    -- [2차]: 훗날 커피 정가가 5,000원으로 올라도 옛날 영수증에는 당시 결제한 4,500원이 그대로 박제되어 있어야 합니다.
    unit_price INTEGER NOT NULL CHECK(unit_price > 0),

    -- [1차]: 외래키 제약: 부모 주문(orders) 삭제 시 상세 품목들도 함께 연쇄 삭제(CASCADE)합니다.
    -- [2차]: 영수증 원본을 파쇄하면 영수증 안의 세부 구매 품목 내역도 함께 휴지통으로 버려집니다.
    FOREIGN KEY (order_id) REFERENCES orders (order_id) ON DELETE CASCADE,

    -- [1차]: 외래키 제약: 메뉴가 과거 주문 상세에 물려있다면 메뉴 삭제를 차단(RESTRICT)합니다.
    -- [2차]: 과거 영수증에 버젓이 찍힌 메뉴를 메뉴판 DB에서 완전히 삭제해버리면 영수증이 훼손되므로 막습니다.
    FOREIGN KEY (menu_id) REFERENCES menus (menu_id) ON DELETE RESTRICT
);
